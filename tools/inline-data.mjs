#!/usr/bin/env node
/**
 * inline-data.mjs — inline releases-snapshot.json + locale/*.json into client.js.
 *
 * Why: the browser-side plugin is loaded through window.__ModuleLoader__ and
 * cannot reliably `import` sibling JSON files (the module loader only resolves
 * declared entries). Inlining makes client.js fully self-contained, so the
 * published npm package needs nothing beyond the files listed in package.json.
 *
 * Run after editing locale/*.json or regenerating releases-snapshot.json:
 *   node tools/build-snapshot.mjs   (optional, needs network)
 *   node tools/inline-data.mjs
 *
 * The region between /* __DATA_START__ * / and /* __DATA_END__ * / is replaced
 * verbatim on every run, so re-running is idempotent.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const clientPath = join(root, 'client.js');

const snapshot = JSON.parse(readFileSync(join(root, 'releases-snapshot.json'), 'utf8'));
const zh = JSON.parse(readFileSync(join(root, 'locale', 'zh.json'), 'utf8'));
const en = JSON.parse(readFileSync(join(root, 'locale', 'en.json'), 'utf8'));

// Trim the bilingual raw bodies: the plugin only renders the parsed Chinese
// groups, so shipping both raw halves would roughly double the file for no
// benefit. Keep a short excerpt for debugging instead.
const slim = {
  generatedAt: snapshot.generatedAt,
  repo: snapshot.repo,
  current: null,
  latest: snapshot.latest,
  releases: snapshot.releases.map((r) => ({
    tag: r.tag,
    version: r.version,
    name: r.name,
    publishedAt: r.publishedAt,
    prerelease: !!r.prerelease,
    url: r.url,
    groups: r.groups,
  })),
};

const payload =
  '    /* __DATA_START__ */\n' +
  '    /* Generated by `node tools/inline-data.mjs` — do not edit by hand. */\n' +
  '    const SNAPSHOT = ' + JSON.stringify(slim) + ';\n' +
  '    const LOCALES = ' + JSON.stringify({ zh, en }) + ';\n' +
  '    /* __DATA_END__ */';

const src = readFileSync(clientPath, 'utf8');
const start = src.indexOf('    /* __DATA_START__ */');
const endMark = '    /* __DATA_END__ */';
const end = src.indexOf(endMark);
if (start < 0 || end < 0 || end < start) {
  throw new Error('client.js is missing the __DATA_START__ / __DATA_END__ markers');
}
const next = src.slice(0, start) + payload + src.slice(end + endMark.length);
writeFileSync(clientPath, next, 'utf8');
console.log(`inlined ${slim.releases.length} releases into client.js (${next.length} bytes)`);
